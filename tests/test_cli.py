import subprocess
import sys


def test_gradle_init_template():
    out = subprocess.run([sys.executable, "-m", "scipq_mcp", "gradle-init"],
                         capture_output=True, text=True, check=True).stdout
    assert "-Xplugin:scip" in out and "build/scip-targetroot" in out


def test_query(sample_root):
    out = subprocess.run([sys.executable, "-m", "scipq_mcp", "query", "--root", sample_root,
                          "impl", "Entity"], capture_output=True, text=True, check=True).stdout
    assert "3 subtypes (2 direct)" in out


def test_init_config_prints_a_template(sample_root):
    import tomllib
    out = subprocess.run([sys.executable, "-m", "scipq_mcp", "init-config", "--root",
                          sample_root], capture_output=True, text=True, check=True).stdout
    assert tomllib.loads(out)["profiles"] == []   # the sample uses no framework annotations
    assert "Nothing here is executed" in out


def test_init_config_proposes_excluding_generated_directories(tmp_path):
    import os
    import tomllib
    from scipq_mcp.graph import generated_dirs
    root = tmp_path / "repo"
    for d, header in (("graph-out", ""), ("wsclient", "// Generated by a tool, do not edit\n"),
                      ("docs2", "")):
        os.makedirs(root / d)
        for k in range(4):
            (root / d / f"f{k}.json" if d != "wsclient" else root / d / f"F{k}.java"
             ).write_text(header + '{"a": 1}\n')
    assert generated_dirs(str(root)) == ["graph-out", "wsclient"]
    out = subprocess.run([sys.executable, "-m", "scipq_mcp", "init-config", "--root", str(root)],
                         capture_output=True, text=True, check=True).stdout
    assert tomllib.loads(out)["by_name"]["exclude"] == ["graph-out/*", "wsclient/*"]


def test_generated_dirs_in_a_mixed_module(tmp_path):
    import os
    from scipq_mcp.graph import generated_dirs
    root = tmp_path / "repo"
    gen = "// Generated by a tool, do not edit\nclass A {}\n"
    for d, n, header in (("ws/src/soap/v1", 10, gen), ("ws/src/soap/v2", 9, gen),
                         ("ws/src/com/example/own", 4, ""), ("app/src/com/example/gen", 3, ""),
                         ("app/web/reports", 3, "")):
        os.makedirs(root / d)
        for k in range(n):
            ext = ".jrxml" if "reports" in d else ".java"
            (root / d / f"F{k}{ext}").write_text(header or "class A {}\n")
    # the generated packages, not the module with own code; a package named gen and report
    # templates are not generated output
    assert generated_dirs(str(root)) == ["ws/src/soap"]


def test_generated_markers_are_file_headers_only():
    from scipq_mcp.graph import generated_header

    def gen(text):
        return generated_header(text.encode())

    assert gen("/*\n * NOTE: This class is auto generated by the codegen program.\n */\n"
               "package a;\npublic class A {}\n")
    assert gen("package a;\nimport javax.annotation.Generated;\n"
               "@Generated(\"org.jsonschema2pojo\")\npublic class Bono {}\n")
    # a designer marks only the members it built; Eclipse leaves stubs in method bodies
    assert not gen("package a;\npublic class Screen {\n  @AutoGenerated\n  private int x;\n}\n")
    assert not gen("package a;\npublic class B {\n  void m() {\n"
                   "    // TODO Auto-generated method stub\n  }\n}\n")
